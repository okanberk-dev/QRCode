// Static brand images used inside mails. Gmail and Outlook strip inline
// <svg>, so icons are served as PNG from public/mail/ (generated by
// scripts/generate-mail-assets.ts). Always absolute URLs — mail clients
// can't resolve relative paths.
export type MailAsset =
  | 'buaze-mark-dark.png'
  | 'buaze-mark-light.png'
  | 'buaze-ecg-lime.png'
  | 'buaze-ecg-graphite.png'
  | 'buaze-instagram.png';

export function mailAssetUrl(name: MailAsset): string {
  const base = (process.env.NEXT_PUBLIC_APP_URL || 'https://www.buaze.com').replace(/\/+$/, '');
  return `${base}/mail/${name}`;
}
