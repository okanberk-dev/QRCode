// Mail typography = Poppins (geometric sans). Web fonts only load in clients
// that honour <link>/@import (Apple Mail, iOS Mail, Gmail app on some
// platforms). Everywhere else the stack falls through to the closest
// geometric/humanist system sans: Segoe UI (Windows/Outlook) → system UI
// (-apple-system, Roboto) → Helvetica Neue → Arial. Every text role uses the
// SAME family; hierarchy comes from weight/size/letter-spacing, not from
// mixing families (the old Space Grotesk + Inter + JetBrains Mono trio made
// the mail look different per client and cost three font downloads).
export const FONT_STACK_SANS =
  "'Poppins', 'Segoe UI', -apple-system, BlinkMacSystemFont, Roboto, 'Helvetica Neue', Helvetica, Arial, sans-serif";

export const FONTS = {
  heading: FONT_STACK_SANS,
  body: FONT_STACK_SANS,
  /** Eyebrows, badges, stat labels, small uppercase tags, tabular numerals.
   *  Same family as body — NOT monospace (the key was `mono` before). */
  label: FONT_STACK_SANS,
  /** Real code only: OTP / verification codes, IP addresses, coupon codes,
   *  token URLs, device fingerprints. Monospace so digits/characters stay
   *  unambiguous and copy-paste friendly. */
  code: "'SF Mono', 'JetBrains Mono', Menlo, Consolas, 'Courier New', monospace",
} as const;

