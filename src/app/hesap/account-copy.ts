export function accountError(copy: Copy, code: string | null | undefined): string {
  return (code && copy.errors[code]) || copy.errors.DEFAULT;
}

/** Calls an /api/customer route; throws `{ code }` on failure. */
export async function customerApi<T = Record<string, unknown>>(
  path: string,
  init?: { method?: string; body?: unknown },
): Promise<{ status: number; data: T }> {
  const res = await fetch(path, {
    method: init?.method ?? (init?.body !== undefined ? 'POST' : 'GET'),
    headers: init?.body !== undefined ? { 'Content-Type': 'application/json' } : undefined,
    body: init?.body !== undefined ? JSON.stringify(init.body) : undefined,
    credentials: 'same-origin',
  });
  const data = (await res.json().catch(() => ({}))) as T & { code?: string; error?: string };
  if (!res.ok && !(res.status === 409 && data.code === 'SIGNUP_REQUIRED')) {
    const err = new Error(data.code ?? data.error ?? 'DEFAULT') as Error & { code: string; status: number };
    err.code = String(data.code ?? data.error ?? 'DEFAULT');
    err.status = res.status;
    throw err;
  }
  return { status: res.status, data };
}

export function errorCode(err: unknown): string {
  return (err as { code?: string })?.code ?? 'DEFAULT';
}

