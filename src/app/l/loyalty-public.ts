// Customer-facing loyalty pages (CLAUDE.md §60): language pick and copy.
export type PublicLocale = 'tr' | 'en';

/** `?lang=en` wins; otherwise the browser's first language. Turkish by default. */
export function pickPublicLocale(langParam: string | undefined, acceptLanguage: string | null): PublicLocale {
  if (langParam === 'en' || langParam === 'tr') return langParam;
  const first = (acceptLanguage ?? '').split(',')[0]?.trim().toLowerCase() ?? '';
  return first.startsWith('en') ? 'en' : 'tr';
}

